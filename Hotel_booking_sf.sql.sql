            THEN TRY_TO_DATE(CHECK_IN_DATE, 'DD/MM/YYYY')
        WHEN TRY_TO_DATE(CHECK_IN_DATE, 'MM/DD/YYYY') IS NOT NULL
            THEN TRY_TO_DATE(CHECK_IN_DATE, 'MM/DD/YYYY')
        WHEN TRY_TO_DATE(CHECK_IN_DATE, 'DD-MM-YYYY') IS NOT NULL
            THEN TRY_TO_DATE(CHECK_IN_DATE, 'DD-MM-YYYY')
        ELSE NULL
    END AS parsed_check_in_date
FROM HOTEL_DB.RAW.HOTEL_BOOKINGS_RAW
LIMIT 20;

CREATE OR REPLACE VIEW HOTEL_DB.ANALYTICS.V_CONFIRMED_BOOKINGS_CLEAN_DATES AS
SELECT
    *,
    CASE
        WHEN TRY_TO_DATE(CHECK_IN_DATE, 'DD/MM/YYYY') IS NOT NULL
            THEN TRY_TO_DATE(CHECK_IN_DATE, 'DD/MM/YYYY')
        WHEN TRY_TO_DATE(CHECK_IN_DATE, 'MM/DD/YYYY') IS NOT NULL
            THEN TRY_TO_DATE(CHECK_IN_DATE, 'MM/DD/YYYY')
        WHEN TRY_TO_DATE(CHECK_IN_DATE, 'DD-MM-YYYY') IS NOT NULL
            THEN TRY_TO_DATE(CHECK_IN_DATE, 'DD-MM-YYYY')
        ELSE NULL
    END AS CHECK_IN_DT
FROM HOTEL_DB.ANALYTICS.V_CONFIRMED_BOOKINGS;


WITH daily_revenue AS (
    SELECT
        CHECK_IN_DT,
        SUM(TOTAL_AMOUNT) AS day_revenue
    FROM HOTEL_DB.ANALYTICS.V_CONFIRMED_BOOKINGS_CLEAN_DATES
    WHERE CHECK_IN_DT IS NOT NULL
    GROUP BY CHECK_IN_DT
)
SELECT
    CHECK_IN_DT,
    day_revenue,
    SUM(day_revenue) OVER (ORDER BY CHECK_IN_DT) AS cumulative_revenue
FROM daily_revenue
ORDER BY CHECK_IN_DT;


