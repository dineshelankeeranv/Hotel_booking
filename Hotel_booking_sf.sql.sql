SELECT
    BOOKING_ID,
    HOTEL_ID,
    HOTEL_CITY,
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CUSTOMER_EMAIL,
    CHECK_IN_DATE,
    CHECK_OUT_DATE,
    ROOM_TYPE,
    NUM_GUESTS,
    TOTAL_AMOUNT,
    CURRENCY,
    BOOKING_STATUS
FROM RAW.HOTEL_BOOKINGS_RAW
WHERE HOTEL_CITY IS NOT NULL
  AND TOTAL_AMOUNT IS NOT NULL;

