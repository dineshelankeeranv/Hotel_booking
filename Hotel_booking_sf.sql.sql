SELECT
    HOTEL_CITY,
    BOOKING_ID,
    ROOM_TYPE,
    NUM_GUESTS,
    TOTAL_AMOUNT,
    RANK() OVER (
        PARTITION BY HOTEL_CITY
        ORDER BY TOTAL_AMOUNT DESC
    ) AS booking_rank_in_city
FROM ANALYTICS.V_CONFIRMED_BOOKINGS
QUALIFY booking_rank_in_city <= 3
ORDER BY HOTEL_CITY, booking_rank_in_city;

WITH daily_revenue AS (
    SELECT
        TO_DATE(CHECK_IN_DATE, 'YYYY-MM-DD') AS check_in_dt,
        SUM(TOTAL_AMOUNT) AS day_revenue
    FROM ANALYTICS.V_CONFIRMED_BOOKINGS
    GROUP BY check_in_dt
)
SELECT
    check_in_dt,
    day_revenue,
    SUM(day_revenue) OVER (
        ORDER BY check_in_dt
    ) AS cumulative_revenue
FROM daily_revenue
ORDER BY check_in_dt;

